/**
 * Get functional part by TAG
 */
export function getFunctionalPart(tag: string): FunctionalPart | undefined {
  return FUNCTIONAL_PARTS_CATALOG[tag.toUpperCase()];
}

/**
 * Get functional parts by category
 */
export function getFunctionalPartsByCategory(category: FunctionalPart['category']): FunctionalPart[] {
  return Object.values(FUNCTIONAL_PARTS_CATALOG).filter(part => part.category === category);
}

