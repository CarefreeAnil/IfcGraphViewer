/**
 * IFC Functional Parts Catalog
 * Based on buildingSMART validation framework
 *
 * Functional parts are used to categorize normative IFC validation rules.
 * Each rule in the Gherkin rules framework has a code like "ALB001", "PJS007", "GEM042"
 * where the 3-letter prefix represents the functional part.
 *
 * References:
 * - Functional Parts: https://github.com/buildingSMART/validate/blob/docs/gh-pages/docs/dev/functional_parts.md
 * - Gherkin Rules: https://buildingsmart.github.io/ifc-gherkin-rules/branches/main/index.html
 */

export interface FunctionalPart {
  tag: string;
  name: string;
  description: string;
  category: 'core' | 'geometry' | 'placement' | 'positioning' | 'organization' | 'properties' | 'presentation' | 'connectivity' | 'management';
}

